import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true });
const base = process.env.TEST_URL || 'http://127.0.0.1:4174/SelfPage/';
await mkdir('.local/reports', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(base, { waitUntil: 'networkidle' });
  await page.evaluate(() => { document.documentElement.style.scrollBehavior = 'auto'; });
  const cursor = page.locator('.animated-cursor');
  const state = async value => {
    await expect(cursor).toHaveAttribute('data-state', value);
    await expect(cursor).toHaveCSS('opacity', '1');
    await expect(cursor.locator('.cursor-sprite')).toHaveCSS('opacity', '1');
    await expect(cursor.locator('.cursor-status')).toHaveCSS('opacity', '1');
  };
  await page.mouse.move(600, 160);
  await expect(cursor).toBeVisible();
  const outfit = await page.locator('html').getAttribute('data-cursor-outfit');
  assert.ok(['short', 'long'].includes(outfit));
  const spriteName = outfit === 'short' ? 'megumi-cursor-short.svg' : 'megumi-cursor.svg';
  assert.ok((await cursor.locator('img').getAttribute('src')).endsWith('/' + spriteName));
  await page.mouse.move(720, 160, { steps: 5 });
  await page.mouse.move(550, 160);
  await page.mouse.move(720, 160, { steps: 5 });
  await state('playful');
  await page.mouse.down();
  await page.waitForTimeout(1200);
  await state('pressed');
  assert.equal(await cursor.locator('.cursor-sprite').evaluate(el => el.getAnimations().length), 0);
  await page.mouse.up();
  await page.locator('.hero-actions .button').hover();
  await state('pointer');
  await page.mouse.down(); await state('pressed');
  await page.mouse.up(); await expect(cursor).toHaveAttribute('data-state', /^(pointer|default)$/);
  assert.equal(await cursor.locator('.cursor-sprite').evaluate(el => getComputedStyle(el).animationName), 'none');
  await page.goto(base, { waitUntil: 'networkidle' });
  await page.evaluate(() => document.documentElement.style.scrollBehavior = 'auto');
  await page.locator('.hero-description').hover();
  await state('text');
  const geometry = () => cursor.locator('img').evaluate(el => getComputedStyle(el).transform);
  await page.mouse.down();
  await state('pressed');
  assert.equal(await geometry(), 'none');
  await page.mouse.up();
  assert.equal(await geometry(), 'none');
  await page.locator('.hero-description').dblclick(); await state('text');
  assert.equal(await page.evaluate(() => getSelection().toString()), '');
  // A wheel can be the first mouse input after keyboard navigation.
  await page.keyboard.press('Shift');
  await expect(cursor).toBeHidden();
  await page.mouse.wheel(0, 90); await state('scroll-down');
  await expect(cursor.locator('.cursor-status')).toHaveText('↓');
  await page.mouse.wheel(0, -90); await state('scroll-up');
  await expect(cursor.locator('.cursor-status')).toHaveText('↑');
  await expect(cursor).not.toHaveAttribute('data-state', /^scroll-/);
  const field = page.locator('#selection-probe');
  await page.evaluate(() => {
    const input = document.createElement('input');
    input.id = 'selection-probe';
    input.value = 'editable';
    document.querySelector('main').prepend(input);
  });
  await field.dblclick({ position: { x: 15, y: 10 } });
  assert.equal(await field.evaluate(el => el.value.slice(el.selectionStart, el.selectionEnd)), 'editable');
  await field.evaluate(el => el.remove());
  await page.waitForTimeout(700);
  await page.locator('.hero-description').hover(); await state('text');
  await page.locator('.hero-image').hover(); await state('grab');
  await page.mouse.down();
  await page.mouse.move(1100, 300, { steps: 8 });
  await state('grabbing');
  // Drag events are browser-managed; cancellation must always restore the cursor.
  await page.mouse.up(); await page.keyboard.press('Escape');
  await page.mouse.move(550, 150);
  await page.evaluate(() => document.querySelector('main').setAttribute('aria-busy', 'true'));
  await state('wait');
  await page.screenshot({ path: '.local/reports/motion-loading.png' });
  await page.evaluate(() => document.querySelector('main').removeAttribute('aria-busy'));
  await page.waitForTimeout(450);
  // Exercise states that have no production control yet without adding fake UI.
  for (const value of ['progress', 'grabbing', 'not-allowed', 'no-drop', 'copy', 'alias', 'zoom-in', 'zoom-out', 'ew-resize', 'ns-resize', 'nesw-resize', 'nwse-resize', 'col-resize', 'row-resize', 'crosshair', 'help', 'move', 'vertical-text']) {
    await page.evaluate(value => document.querySelector('.hero-description').dataset.cursor = value, value);
    await page.locator('.hero-description').hover(); await state(value);
  }
  await page.evaluate(() => delete document.querySelector('.hero-description').dataset.cursor);
  await page.mouse.click(550, 160, { button: 'right' });
  await page.keyboard.press('Escape');
  await page.mouse.move(500, 160);

  await page.evaluate(() => window.scrollTo(0, 0));
  await page.waitForTimeout(100);
  const start = await page.locator('.hero-art').evaluate(el => getComputedStyle(el).translate);
  await page.screenshot({ path: '.local/reports/motion-top.png' });
  await page.evaluate(() => window.scrollTo(0, 500));
  await page.waitForTimeout(100);
  const end = await page.locator('.hero-art').evaluate(el => getComputedStyle(el).translate);
  assert.notEqual(start, end, 'Hero art should follow scroll progress');
  await page.screenshot({ path: '.local/reports/motion-scroll.png' });
  await page.locator('#projects').scrollIntoViewIfNeeded();
  await page.waitForTimeout(100);
  const card = page.locator('.project-card').first();
  await card.hover({ position: { x: 70, y: 65 } });
  await expect(card).toHaveAttribute('data-pointer-inside', 'true');
  assert.notEqual(await card.evaluate(el => el.style.getPropertyValue('--tilt-x')), '0deg');
  await page.screenshot({ path: '.local/reports/pointer-card.png' });
  await card.click({ position: { x: 70, y: 65 } });
  assert.ok(await card.evaluate(el => el.getAnimations({ subtree: true }).some(a => a.effect?.pseudoElement === '::after')));
  await page.mouse.move(400, 160);
  await expect(card).not.toHaveAttribute('data-pointer-inside', 'true');
  await page.screenshot({ path: '.local/reports/motion-projects.png' });
  const first = await page.locator('.projects-intro').boundingBox();
  await page.mouse.wheel(0, Math.max(400, first.y - 138 + 100));
  await page.waitForTimeout(500);
  const later = await page.locator('.projects-intro').boundingBox();
  assert.ok(Math.abs(later.y - 138) < 3, `Project intro pins below the header: initial=${first.y}, after=${later.y}`);
  await page.mouse.wheel(0, 200);
  await page.waitForTimeout(300);
  assert.ok(Math.abs((await page.locator('.projects-intro').boundingBox()).y - later.y) < 3);
  await page.getByRole('button', { name: '项目速览：随手办' }).click();
  await expect(page.locator('dialog')).toBeVisible();
  await page.locator('dialog h2').hover(); await state('text');
  assert.equal(await cursor.evaluate(el => el.matches(':popover-open')), true);
  await page.screenshot({ path: '.local/reports/motion-dialog.png' });
  await page.keyboard.press('Escape');
  await expect(page.locator('dialog')).toHaveCount(0);
  await expect(cursor).toBeHidden();
  const like = page.locator('.like-button');
  await like.click();
  await expect(like).toHaveAttribute('aria-pressed', 'true');
  await state('like');
  await page.screenshot({ path: '.local/reports/pointer-thanks.png' });
  await like.click();
  await expect(like).toHaveAttribute('aria-pressed', 'false');
  await state('reconsidered');
  assert.equal(await geometry(), 'none');
  assert.equal((await cursor.textContent()).trim(), '');
  await page.locator('.avatar-button').click();
  await state('greeting');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.mouse.move(300, 160);
  await expect(cursor).toBeHidden();
  assert.equal(await page.locator('[data-pointer-inside]').count(), 0);
  assert.match(await page.locator('body').evaluate(el => getComputedStyle(el).cursor), /data:image\/svg\+xml;base64,/);
  const touch = await browser.newPage({ hasTouch: true, isMobile: true, viewport: { width: 375, height: 812 } });
  await touch.goto(base, { waitUntil: 'networkidle' });
  await expect(touch.locator('.animated-cursor')).toBeHidden();
  assert.deepEqual(errors, []);
  console.log('Quiet presses, contextual replies, card tilt/ripple, cursor states, dialogs, touch and reduced motion passed.');
} finally { await browser.close(); }
